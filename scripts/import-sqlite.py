#!/usr/bin/env python3
"""Generate config.yml from a previous gateway's SQLite configuration seed.

Only the channel and API-key configuration tables are read; request, usage,
trace and body tables are never touched.

Usage:
    python3 scripts/import-sqlite.py --seed /path/config.db \
        --api-key-file /path/api-key.json --out config.yml

Any literal key in the output must be kept mode 0600 and out of version
control. Prefer ${ENV_VAR} references in config.yml for production.
"""
import json
import os
import sqlite3
import sys

DEFAULT_SEED = "config.db"
DEFAULT_OUT = "config.yml"
API_KEY_FILE = "api-key.json"


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", default=DEFAULT_SEED)
    parser.add_argument("--api-key-file", default=None)
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args()
    seed, out = args.seed, args.out
    api_key_file = args.api_key_file
    conn = sqlite3.connect(seed)
    conn.row_factory = sqlite3.Row

    channels = []
    for row in conn.execute(
        "select name,type,base_url,status,credentials,supported_models,ordering_weight,settings "
        "from channels where deleted_at=0 and status='enabled' order by ordering_weight desc, id"
    ):
        if row["type"] not in ("anthropic", "zhipu_anthropic"):
            continue
        credentials = json.loads(row["credentials"] or "{}")
        settings = json.loads(row["settings"] or "{}") or {}
        mappings = [
            {"from": item["from"], "to": item["to"]}
            for item in (settings.get("modelMappings") or [])
            if item.get("from") and item.get("to")
        ]
        channels.append(
            {
                "name": row["name"],
                "base_url": row["base_url"].rstrip("/"),
                "api_key": credentials.get("apiKey", ""),
                "auth": "x-api-key",
                "models": json.loads(row["supported_models"] or "[]"),
                "mappings": mappings,
                "hide_mapped_models": bool(settings.get("hideMappedModels", False)),
                "priority": int(row["ordering_weight"] or 0),
                "enabled": True,
                "pass_through_user_agent": settings.get("passThroughUserAgent", True) is not False,
                "pass_through_body": settings.get("passThroughBody", True) is not False,
            }
        )

    api_keys = []
    if api_key_file and os.path.exists(api_key_file):
        try:
            api_keys = [json.load(open(api_key_file))["data"]["createAPIKey"]["key"]]
        except Exception:
            pass

    def scalar(value):
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, (int, float)):
            return str(value)
        return json.dumps(value, ensure_ascii=False)

    lines = [
        "# Generated by scripts/import-sqlite.py from a gateway configuration seed.",
        "# Contains upstream credentials: mode 0600, never commit.",
        "listen: 127.0.0.1:8090",
        "max_attempts: 3",
        "connect_timeout_secs: 10",
        "request_timeout_secs: 1800",
        "default_max_tokens: 4096",
        "log_requests: false",
        "api_keys:",
    ]
    for key in api_keys:
        lines.append(f"  - {scalar(key)}")
    lines.append("channels:")
    for channel in channels:
        lines.append(f"  - name: {scalar(channel['name'])}")
        lines.append(f"    base_url: {scalar(channel['base_url'])}")
        lines.append(f"    api_key: {scalar(channel['api_key'])}")
        lines.append(f"    auth: {channel['auth']}")
        lines.append("    models:")
        for model in channel["models"]:
            lines.append(f"      - {scalar(model)}")
        if channel["mappings"]:
            lines.append("    mappings:")
            for mapping in channel["mappings"]:
                lines.append(f"      - from: {scalar(mapping['from'])}")
                lines.append(f"        to: {scalar(mapping['to'])}")
        lines.append(f"    hide_mapped_models: {scalar(channel['hide_mapped_models'])}")
        lines.append(f"    priority: {channel['priority']}")
        lines.append(f"    pass_through_user_agent: {scalar(channel['pass_through_user_agent'])}")
        lines.append(f"    pass_through_body: {scalar(channel['pass_through_body'])}")

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    os.chmod(out, 0o600)
    print(f"wrote {out}: {len(channels)} channels, {len(api_keys)} api keys")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
